# Generates init/10-schema.sql and init/20-data.sql for one platform version: deploys the real database
# image, keeps only what api-v2 of the same version needs (see subset.py) and replaces generated secrets
# with mock values (see mock-seed.sql).
#
# Needs: docker, git, python3, access to mybuildingsmeu1.azurecr.io (az acr login -n mybuildingsmeu1) and
# to the api-v2 repository. Usage: scripts/generate.sh v26.4.3
set -euo pipefail

VERSION=${1:?usage: $0 <platform version, e.g. v26.4.3>}
API_VERSION=${API_VERSION:-$VERSION}  # api-v2 tag when it differs from the database version
ROOT=$(cd "$(dirname "$0")/.." && pwd)
WORK="$ROOT/.generate"
POSTGRES_IMAGE=${POSTGRES_IMAGE:-mybuildingsmeu1.azurecr.io/eliona/core/postgres16:latest-20260918}
DATABASE_IMAGE=mybuildingsmeu1.azurecr.io/eliona/core/database:$VERSION
API_REPO=${API_REPO:-git@ssh.dev.azure.com:v3/eliona/core/api-v2}
NET=eliona-mock-generate
DB=eliona-mock-generate-db

cleanup() { docker rm -f "$DB" >/dev/null 2>&1 || true; docker network rm "$NET" >/dev/null 2>&1 || true; }
trap cleanup EXIT
mkdir -p "$WORK"

echo "api-v2 $API_VERSION source"
git -C "$WORK/api-v2" fetch --depth 1 origin tag "$API_VERSION" 2>/dev/null \
    || git clone --quiet --depth 1 --branch "$API_VERSION" "$API_REPO" "$WORK/api-v2"
git -C "$WORK/api-v2" checkout --quiet "$API_VERSION"

echo "database $VERSION"
cleanup
docker network create "$NET" >/dev/null
docker run -d --name "$DB" --network "$NET" -e POSTGRES_PASSWORD=secret "$POSTGRES_IMAGE" >/dev/null
until docker exec "$DB" pg_isready -U postgres >/dev/null 2>&1; do sleep 1; done
docker run --rm --network "$NET" \
    -e CONNECTION_STRING="postgres://postgres:secret@$DB:5432/postgres" \
    -e INIT_CONNECTION_STRING="postgres://postgres:secret@$DB:5432/postgres" \
    "$DATABASE_IMAGE" > "$WORK/database-init.log" 2>&1 \
    || { echo "database init failed, see $WORK/database-init.log"; exit 1; }

docker cp "$ROOT/scripts/mock-seed.sql" "$DB:/tmp/mock-seed.sql"
docker exec "$DB" psql -U postgres -q -v ON_ERROR_STOP=1 -f /tmp/mock-seed.sql

echo "subset for api-v2"
docker exec "$DB" pg_dump -U postgres -Fc --schema-only --quote-all-identifiers --no-owner --no-privileges --no-comments \
    -f /tmp/schema.dump postgres 2>/dev/null
docker exec "$DB" pg_restore -l /tmp/schema.dump > "$WORK/toc.txt"
PSQL="docker exec -i $DB psql -U postgres -At" python3 -I "$ROOT/scripts/subset.py" "$WORK/api-v2" "$WORK/toc.txt" > "$WORK/toc-subset.txt"
docker cp "$WORK/toc-subset.txt" "$DB:/tmp/toc-subset.txt"

header() { printf -- '-- Generated by scripts/generate.sh from platform version %s - do not edit.\n\n' "$VERSION"; }
{ header; docker exec "$DB" pg_restore --no-owner --no-privileges --no-comments -L /tmp/toc-subset.txt -f - /tmp/schema.dump; } \
    > "$ROOT/init/10-schema.sql"

tables=$(grep -E '^[0-9]+; [0-9]+ [0-9]+ TABLE ' "$WORK/toc-subset.txt" | awk '{print "-t " $5 "." $6}')
# shellcheck disable=SC2086
{ header; docker exec "$DB" pg_dump -U postgres --data-only --quote-all-identifiers --no-owner --no-privileges \
    --disable-triggers $tables postgres 2>/dev/null; } > "$ROOT/init/20-data.sql"

roles=$(docker exec "$DB" psql -U postgres -At -c \
    "select string_agg(format('CREATE ROLE %I NOLOGIN;', rolname), E'\n' order by rolname) from pg_roles where rolname !~ '^pg_' and rolname <> 'postgres'")
{ header; echo "$roles"; } > "$ROOT/init/00-roles.sql"

echo "$VERSION" > "$ROOT/init/VERSION"
echo "done: init/00-roles.sql, init/10-schema.sql ($(wc -l < "$ROOT/init/10-schema.sql") lines), init/20-data.sql ($(wc -l < "$ROOT/init/20-data.sql") lines)"
